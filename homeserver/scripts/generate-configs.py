# ---------------------------------------------------------------------------
# Paths — derived from script location, not hardcoded
# ---------------------------------------------------------------------------
STACK_DIR: Path      = Path(__file__).resolve().parent.parent   # homeserver/
ENV_FILE: Path       = STACK_DIR / ".env"           # user-edited credentials
GENERATED_FILE: Path = STACK_DIR / "generated.env"  # machine-written, gitignored
DOCKER_ENV: Path     = STACK_DIR / ".env.docker"    # merged, single-file env
CONFIGS: Path        = STACK_DIR / "configs"

# ---------------------------------------------------------------------------
# .env loader / writer
# ---------------------------------------------------------------------------
def _parse_env_file(path: Path) -> dict:
    env = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if "=" in line:
                key, _, val = line.partition("=")
                val = val.split("#")[0].strip()
                env[key.strip()] = val
    return env

def load_env(*paths: Path) -> dict:
    """Load and merge one or more env files. Later files win on conflict."""
    env = {}
    for path in paths:
        if not path.exists():
            continue
        env.update(_parse_env_file(path))
    if not ENV_FILE.exists():
        print(f"ERROR: {ENV_FILE} not found.")
        print(f"  cp {ENV_FILE.parent}/.env.example {ENV_FILE}")
        sys.exit(1)
    return env

def write_back_to_env(path: Path, updates: dict):
    """Update existing keys in path in place; append any not found."""
    lines = path.read_text().splitlines(keepends=True) if path.exists() else []
    found = set()
    out = []
    for line in lines:
        stripped = line.strip()
        if "=" in stripped and not stripped.startswith("#"):
            key = stripped.partition("=")[0].strip()
            if key in updates:
                out.append(f"{key}={updates[key]}\n")
                found.add(key)
                continue
        out.append(line)
    for key, val in updates.items():
        if key not in found:
            out.append(f"{key}={val}\n")
    path.write_text("".join(out))
    path.chmod(0o600)

def write_generated(updates: dict):
    """Write (or update) generated.env with machine-generated values."""
    existing = _parse_env_file(GENERATED_FILE) if GENERATED_FILE.exists() else {}
    existing.update(updates)
    lines = ["# Auto-generated by scripts — do not edit by hand\n"]
    for k, v in existing.items():
        lines.append(f"{k}={v}\n")
    GENERATED_FILE.write_text("".join(lines))
    GENERATED_FILE.chmod(0o600)

def write_merged_docker_env():
    """Write .env.docker = .env + generated.env merged — convenience for tooling that takes a single --env-file."""
    merged = {}
    for path in (ENV_FILE, GENERATED_FILE):
        if path.exists():
            merged.update(_parse_env_file(path))
    lines = ["# Merged env — auto-generated, do not edit\n"]
    for k, v in merged.items():
        lines.append(f"{k}={v}\n")
    DOCKER_ENV.write_text("".join(lines))
    DOCKER_ENV.chmod(0o600)

# ---------------------------------------------------------------------------
# Input validators
# Each returns the validated value, or raises ValueError with a user-facing
# message. ask() catches the error and reprompts.
# ---------------------------------------------------------------------------
ZONEINFO = Path("/usr/share/zoneinfo")

def validate_tz(val: str) -> str:
    # /usr/share/zoneinfo exists on every Unraid host and every modern Linux.
    # On platforms where it doesn't (e.g. running this script on macOS for
    # testing), skip validation rather than rejecting every timezone.
    if ZONEINFO.exists() and not (ZONEINFO / val).is_file():
        raise ValueError(f"not a valid timezone (no {ZONEINFO}/{val})")
    return val

def validate_ip(val: str) -> str:
    try:
        ipaddress.ip_address(val)
    except ValueError as e:
        raise ValueError(f"not a valid IP address: {e}") from e
    return val

def validate_cidr(val: str) -> str:
    try:
        ipaddress.ip_network(val, strict=False)
    except ValueError as e:
        raise ValueError(f"not a valid CIDR: {e}") from e
    return val

# ---------------------------------------------------------------------------
# Interactive prompts
# ---------------------------------------------------------------------------
def ask(label: str, default: str = "", hint: str = "",
        validator: Optional[Callable[[str], str]] = None) -> str:
    """Prompt until a non-empty value is entered and (optionally) validates.
    Returns default if provided and input is blank.
    """
    if hint:
        print(f"    {hint}")
    suffix = f" [{default}]" if default else ""
    while True:
        val = input(f"  {label}{suffix}: ").strip()
        if not val and default:
            val = default
        if not val:
            print("    Required.")
            continue
        if validator is not None:
            try:
                return validator(val)
            except ValueError as e:
                print(f"    Invalid: {e}")
                continue
        return val

def prompt_for_missing(env: dict) -> dict:
    """
    Prompt for any missing required values. Returns a dict of new values
    collected — caller is responsible for merging into env and writing back.
    """
    updates = {}

    def get_or_ask(key: str, label: str, default: str = "", hint: str = "",
                   validator: Optional[Callable[[str], str]] = None) -> str:
        val = env.get(key, "").strip()
        if val:
            return val
        val = ask(label, default=default, hint=hint, validator=validator)
        updates[key] = val
        return val

    missing = [
        k for k in [
            "TZ", "TAILNET_NAME",
            "PLEX_LAN_IP", "PLEX_LAN_SUBNET",
            "VPN_PRIVATE_KEY", "VPN_ADDRESS", "VPN_CITY",
            "USENET_HOST", "USENET_USER", "USENET_PASS",
            "NZBGEEK_API_KEY", "NZBPLANET_API_KEY",
        ]
        if not env.get(k, "").strip()
    ]

    if not missing:
        return updates  # nothing to ask

    print("\nSome required values are missing from .env. Let's fill them in.\n")

    # System
    if "TZ" in missing:
        print("--- System ---")
        get_or_ask("TZ", "Timezone",
                   default="America/Los_Angeles",
                   hint="e.g. America/New_York, America/Los_Angeles, Europe/London",
                   validator=validate_tz)

    if "TAILNET_NAME" in missing:
        print("--- Tailscale ---")
        # Required, not optional: write_sabnzbd() puts this in SAB's
        # host_whitelist. SAB returns 403 for any Host header it does not know,
        # and `tailscale serve` passes the original Host through — so a blank
        # value produces a SAB that works perfectly on loopback and 403s from
        # every tailnet device. Prompting is the only thing that stops that
        # being discovered days later.
        get_or_ask("TAILNET_NAME", "Tailnet MagicDNS domain",
                   hint="`tailscale status` or admin console -> DNS, "
                        "no leading dot (e.g. tail1a2b3.ts.net)")

    # Network / Plex
    net_missing = [k for k in ["PLEX_LAN_IP", "PLEX_LAN_SUBNET"] if k in missing]
    if net_missing:
        print("\n--- Network ---")
        if "PLEX_LAN_IP" in missing:
            get_or_ask("PLEX_LAN_IP", "Server LAN IP",
                       hint="shown in Unraid UI top-right corner, e.g. 192.168.1.50",
                       validator=validate_ip)
        if "PLEX_LAN_SUBNET" in missing:
            get_or_ask("PLEX_LAN_SUBNET", "LAN subnet (CIDR)",
                       hint="e.g. 192.168.1.0/24  — run: ip route | grep default",
                       validator=validate_cidr)

    # Mullvad WireGuard — for Gluetun outbound VPN on SAB + Prowlarr
    vpn_missing = [k for k in ["VPN_PRIVATE_KEY", "VPN_ADDRESS", "VPN_CITY"] if k in missing]
    if vpn_missing:
        print("\n--- Mullvad WireGuard (Gluetun outbound VPN) ---")
        print("  Generate a config at mullvad.net/account → WireGuard configuration.")
        if "VPN_PRIVATE_KEY" in missing:
            get_or_ask("VPN_PRIVATE_KEY", "WireGuard private key",
                       hint="from [Interface] PrivateKey = ... in the downloaded .conf")
        if "VPN_ADDRESS" in missing:
            get_or_ask("VPN_ADDRESS", "WireGuard address",
                       hint="from [Interface] Address = ... (comma-separated v4,v6)")
        if "VPN_CITY" in missing:
            get_or_ask("VPN_CITY", "Exit city",
                       default="Amsterdam",
                       hint="pick one near your Usenet provider for lowest latency")

    # Usenet
    usenet_missing = [k for k in ["USENET_HOST", "USENET_USER", "USENET_PASS"] if k in missing]
    if usenet_missing:
        print("\n--- Usenet (primary provider) ---")
        get_or_ask("USENET_HOST", "Provider hostname", hint="e.g. news.newshosting.com")
        get_or_ask("USENET_USER", "Username")
        get_or_ask("USENET_PASS", "Password")
        if not env.get("USENET_CONNECTIONS", "").strip():
            val = ask("Max connections", default="20", hint="check your plan — Newshosting Unlimited = 30+")
            if val != "20":
                updates["USENET_CONNECTIONS"] = val

    # Optional fill server
    fill_keys = ["USENET_FILL_HOST", "USENET_FILL_USER", "USENET_FILL_PASS"]
    has_fill = any(env.get(k, "").strip() for k in fill_keys)
    if not has_fill:
        ans = input("\n  Add a fill/backup Usenet server (different backbone)? [y/N]: ").strip().lower()
        if ans == "y":
            updates["USENET_FILL_HOST"] = ask("Fill server hostname")
            updates["USENET_FILL_USER"] = ask("Fill server username")
            updates["USENET_FILL_PASS"] = ask("Fill server password")

    # Indexers
    idx_missing = [k for k in ["NZBGEEK_API_KEY", "NZBPLANET_API_KEY"] if k in missing]
    if idx_missing:
        print("\n--- Indexers ---")
        if "NZBGEEK_API_KEY" in missing:
            get_or_ask("NZBGEEK_API_KEY", "NZBGeek API key", hint="nzbgeek.info → My Profile → API Key")
        if "NZBPLANET_API_KEY" in missing:
            get_or_ask("NZBPLANET_API_KEY", "NZBPlanet API key", hint="nzbplanet.net → My Account → API Key")

    # Plex server name (optional, has default)
    if not env.get("PLEX_SERVER_NAME", "").strip():
        print("\n--- Plex ---")
        val = ask("Plex server name (shown in clients)", default="Home Media Server")
        if val != "Home Media Server":
            updates["PLEX_SERVER_NAME"] = val

    return updates


