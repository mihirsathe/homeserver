#!/usr/bin/env python3
"""
generate-configs.py
===================
Interactive setup script. Run once before starting the stack.

  cd /mnt/user/appdata/homeserver/homeserver
  python3 scripts/generate-configs.py

What it does:
  1. Prompts for any credentials not yet in .env, writes them back
  2. Auto-generates STACK_DIR, UUID API keys and the Nextcloud passwords
     into generated.env
  3. Writes a merged .env.docker (convenience single-file env for `docker compose --env-file`)
  4. Writes all app config files to configs/ so no setup wizard is needed
  5. Creates the /mnt/user/data/ directory structure

Two env files:
  .env          — what you type (credentials, settings)
  generated.env — what the script writes (API keys, paths, tokens)

Safe to re-run — skips prompts for values already set, won't overwrite
existing API keys, and mkdir -p is idempotent.

Uses only stdlib — no pip dependencies.
"""

