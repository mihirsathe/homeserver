# Configure Prowlarr: add indexers, connect arr apps, sync
# ---------------------------------------------------------------------------
def configure_prowlarr(base: str, key: str, env: dict) -> None:

    def add_indexer(name: str, schema_name: str, api_key_value: str) -> None:
        if already_exists(base, key, "/api/v1/indexer", "name", name):
            print(f"  ✓ Prowlarr: {name} already added")
            return
        try:
            schemas = arr_get(base, key, "/api/v1/indexer/schema")
        except Exception as e:
            print(f"  ⚠ Prowlarr: could not fetch schemas: {e}")
            return
        # Match on schema 'name' (e.g. "NZBgeek", "NzbPlanet") — not on
        # 'definitionName', which is the protocol family ("Newznab",
        # "Torznab"). Every Newznab-based indexer shares the same
        # definitionName, so matching that can't disambiguate. Compare
        # case-insensitively to tolerate upstream casing shifts (NZBgeek
        # vs NZBGeek, etc.).
        schema = next(
            (s for s in schemas if (s.get("name") or "").lower() == schema_name.lower()),
            None
        )
        if not schema:
            print(f"  ⚠ Prowlarr: schema not found for '{schema_name}' — check indexer name")
            return
        for field in schema.get("fields", []):
            if field.get("name") == "apiKey":
                field["value"] = api_key_value
        schema["name"] = name
        schema["enable"] = True
        schema["appProfileId"] = 1
        try:
            arr_post(base, key, "/api/v1/indexer", schema)
            print(f"  ✓ Prowlarr: {name} added")
        except Exception as e:
            print(f"  ⚠ Prowlarr: failed to add {name}: {e}")

    # Newznab category IDs: 2000s = Movies, 5000s = TV, 3000s = Audio.
    sync_categories = {
        "Radarr": [2000, 2010, 2020, 2030, 2040, 2045, 2050, 2060],
        "Sonarr": [5000, 5010, 5020, 5030, 5040, 5045, 5050, 5060, 5070, 5080],
        "Lidarr": [3000, 3010, 3020, 3030, 3040],
    }

    def add_app(name: str, app_url: str, app_key: str, impl: str, contract: str) -> None:
        # Both Prowlarr and the *arrs serve at root now (UrlBase stripped);
        # URLs carry no urlbase suffix. prowlarrUrl points the *arr back at
        # Prowlarr through gluetun's netns alias because Prowlarr itself has
        # no bridge endpoint of its own. syncCategories pulled from the
        # per-app map above so Sonarr/Lidarr get TV/Audio categories instead
        # of Movies — reconcile_fields propagates this to any pre-existing
        # Sonarr/Lidarr entries that were created with the wrong list.
        desired_fields = {
            "prowlarrUrl":    "http://gluetun:9696",
            "baseUrl":        app_url,
            "apiKey":         app_key,
            "syncCategories": sync_categories[name],
        }
        existing_apps = arr_get(base, key, "/api/v1/applications")
        existing = next((a for a in existing_apps if a.get("name") == name), None)
        if existing is not None:
            if reconcile_fields(existing, fields=desired_fields):
                try:
                    arr_put(base, key, f"/api/v1/applications/{existing['id']}", existing)
                    print(f"  ✓ Prowlarr: {name} reconciled")
                except Exception as e:
                    print(f"  ⚠ Prowlarr: failed to reconcile {name}: {e}")
            else:
                print(f"  ✓ Prowlarr: {name} already connected")
            return
        try:
            arr_post(base, key, "/api/v1/applications", {
                "name": name,
                "syncLevel": "fullSync",
                "fields": [{"name": k, "value": v} for k, v in desired_fields.items()],
                "implementationName": name,
                "implementation": impl,
                "configContract": contract,
                "tags": []
            })
            print(f"  ✓ Prowlarr: {name} connected")
        except Exception as e:
            print(f"  ⚠ Prowlarr: failed to connect {name}: {e}")

    add_indexer("NZBGeek",   "nzbgeek",   require(env, "NZBGEEK_API_KEY"))
    add_indexer("NZBPlanet", "nzbplanet", require(env, "NZBPLANET_API_KEY"))

    add_app("Radarr", "http://radarr:7878",
            require(env, "RADARR_API_KEY"),   "Radarr", "RadarrSettings")
    add_app("Sonarr", "http://sonarr:8989",
            require(env, "SONARR_API_KEY"),   "Sonarr", "SonarrSettings")
    add_app("Lidarr", "http://lidarr:8686",
            require(env, "LIDARR_API_KEY"),   "Lidarr", "LidarrSettings")

    # Trigger sync
    try:
        requests.post(f"{base}/api/v1/applications/sync",
                      headers={"X-Api-Key": key}, timeout=15)
        print("  ✓ Prowlarr: indexer sync triggered")
    except Exception as e:
        print(f"  ⚠ Prowlarr: sync trigger failed: {e}")

