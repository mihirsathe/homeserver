# Main
# ---------------------------------------------------------------------------
def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Wire the homeserver stack together via API after first boot."
    )
    p.add_argument(
        "--stack-dir", type=Path,
        help="Override the homeserver/ directory (default: inferred from script location)"
    )
    p.add_argument(
        "--timeout", type=int, default=180,
        help="Per-service wait timeout in seconds (default: 180)"
    )
    return p.parse_args()


def main() -> None:
    global STACK_DIR, ENV_FILE, GENERATED_FILE, DOCKER_ENV
    args = _parse_args()
    if args.stack_dir:
        STACK_DIR = args.stack_dir.resolve()
        ENV_FILE = STACK_DIR / ".env"
        GENERATED_FILE = STACK_DIR / "generated.env"
        DOCKER_ENV = STACK_DIR / ".env.docker"

    env = load_env()
    lan_ip = require(env, "PLEX_LAN_IP")
    sabnzbd_key = require(env, "SABNZBD_API_KEY")

    SERVICES = {
        "radarr":   (f"http://localhost:7878/radarr",   require(env, "RADARR_API_KEY")),
        "sonarr":   (f"http://localhost:8989/sonarr",   require(env, "SONARR_API_KEY")),
        "lidarr":   (f"http://localhost:8686/lidarr",   require(env, "LIDARR_API_KEY")),
        "prowlarr": (f"http://localhost:9696/prowlarr", require(env, "PROWLARR_API_KEY")),
    }

    print("\n=== Waiting for services ===\n")
    wait_for("http://localhost:8080/sabnzbd/api?mode=version", "sabnzbd",
             timeout=args.timeout)
    for name, (url, _key) in SERVICES.items():
        api_ver = "v1" if name == "prowlarr" else "v3"
        wait_for(f"{url}/api/{api_ver}/system/status", name, timeout=args.timeout)
    wait_for("http://localhost:5055", "seerr", timeout=args.timeout)

    print("\n=== Radarr ===\n")
    url, key = SERVICES["radarr"]
    configure_arr("Radarr", url, key, "/data/media/movies", "movies", sabnzbd_key)

    print("\n=== Sonarr ===\n")
    url, key = SERVICES["sonarr"]
    configure_arr("Sonarr", url, key, "/data/media/tv", "tv", sabnzbd_key,
                  extra_mm={"createEmptySeriesFolders": False})

    print("\n=== Lidarr ===\n")
    url, key = SERVICES["lidarr"]
    configure_arr("Lidarr", url, key, "/data/media/music", "music", sabnzbd_key)

    print("\n=== Prowlarr ===\n")
    url, key = SERVICES["prowlarr"]
    configure_prowlarr(url, key, env)

    print("\n=== Plex ===\n")
    plex_token = get(env, "PLEX_TOKEN")
    if not plex_token:
        print("  Plex token not found in .env.")
        print(f"  1. Open http://{lan_ip}:32400/web in your browser")
        print("  2. Sign in with your Plex account")
        print("  3. Settings → General → scroll to bottom → click 'Show'")
        print("  4. Copy the X-Plex-Token value\n")
        # getpass suppresses terminal echo and keeps the token out of shell history.
        plex_token = getpass.getpass("  Paste PLEX_TOKEN here (or press Enter to skip): ").strip()
        if plex_token:
            write_generated({"PLEX_TOKEN": plex_token})
            refresh_docker_env()
            print("  ✓ PLEX_TOKEN saved to generated.env\n")

    plex = None
    if plex_token:
        plex = configure_plex(plex_token, lan_ip)
        # PLEX_CLAIM tokens are single-use and expire after ~4 minutes.
        # Once we've got a PLEX_TOKEN the claim is spent — blank it so a later
        # redeploy doesn't feed a dead claim into a freshly-recreated Plex.
        if get(env, "PLEX_CLAIM"):
            write_generated({"PLEX_CLAIM": ""})
            refresh_docker_env()
            print("  ✓ PLEX_CLAIM cleared (one-time-use, already consumed)")
    else:
        print("  ⚠ Skipped — re-run this script after signing into Plex")

    print("\n=== Tautulli ===\n")
    if plex is not None:
        configure_tautulli(plex, plex_token)
    else:
        print("  ⚠ Skipped — needs a working Plex connection from the previous step")

    print("\n=== Done ===\n")
    print("Stack is fully configured. Access points:")
    print(f"  SABnzbd:   http://{lan_ip}:8080/sabnzbd")
    print(f"  Prowlarr:  http://{lan_ip}:9696/prowlarr")
    print(f"  Radarr:    http://{lan_ip}:7878/radarr")
    print(f"  Sonarr:    http://{lan_ip}:8989/sonarr")
    print(f"  Lidarr:    http://{lan_ip}:8686/lidarr")
    print(f"  Plex:      http://{lan_ip}:32400/web")
    print(f"  Seerr:     http://{lan_ip}:5055")
    print()
    print("Admin UIs (everything above except Plex) are reachable via")
    print("Tailscale MagicDNS from any device on your tailnet.")
    print()
    print("Remaining manual steps:")
    print("  1. Plex → Settings → Transcoder → Use hardware acceleration when")
    print("     available → select NVIDIA GeForce RTX 3050 (requires Plex Pass —")
    print("     cannot be set via API).")
    print("  2. Seerr → sign in with your Plex account, then Settings → Users →")
    print("     edit each family member → grant 'Auto-Request' so their Plex")
    print("     Watchlist additions become Radarr/Sonarr requests automatically.")
    print("     (Per-user grant; Seerr ties it to each Plex SSO identity.)")
    print(f"  3. Profilarr → http://{lan_ip}:6868 → add Radarr + Sonarr as sync")
    print("     targets (paste URLs + API keys from generated.env), subscribe to")
    print("     the Dictionarry DB and/or TRaSH Guides, select profiles, sync.")
    print("     Profilarr has no API-driven bootstrap path.")

if __name__ == "__main__":
    main()
