# ---------------------------------------------------------------------------
# Paths and env loading
# Paths are module-level but mutable at argparse time (via --stack-dir)
# before main() dispatches.
# ---------------------------------------------------------------------------
STACK_DIR: Path      = Path(__file__).resolve().parent.parent   # homeserver/
ENV_FILE: Path       = STACK_DIR / ".env"
GENERATED_FILE: Path = STACK_DIR / "generated.env"
DOCKER_ENV: Path     = STACK_DIR / ".env.docker"

def _parse_env_file(path: Path) -> dict:
    env = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if "=" in line:
                key, _, val = line.partition("=")
                val = val.split("#")[0].strip()
                env[key.strip()] = val
    return env

def load_env() -> dict:
    """Load and merge .env and generated.env. generated.env wins on conflict."""
    if not ENV_FILE.exists():
        print(f"ERROR: {ENV_FILE} not found — run generate-configs.py first")
        sys.exit(1)
    env = _parse_env_file(ENV_FILE)
    if GENERATED_FILE.exists():
        env.update(_parse_env_file(GENERATED_FILE))
    return env

def write_generated(updates: dict) -> None:
    """Append or update keys in generated.env."""
    existing = _parse_env_file(GENERATED_FILE) if GENERATED_FILE.exists() else {}
    existing.update(updates)
    lines = ["# Auto-generated by scripts — do not edit by hand\n"]
    for k, v in existing.items():
        lines.append(f"{k}={v}\n")
    GENERATED_FILE.write_text("".join(lines))
    GENERATED_FILE.chmod(0o600)

def refresh_docker_env() -> None:
    """Rewrite .env.docker after generated.env changes."""
    merged = {}
    for path in (ENV_FILE, GENERATED_FILE):
        if path.exists():
            merged.update(_parse_env_file(path))
    lines = ["# Merged env — auto-generated, do not edit\n"]
    for k, v in merged.items():
        lines.append(f"{k}={v}\n")
    DOCKER_ENV.write_text("".join(lines))
    DOCKER_ENV.chmod(0o600)

def require(env: dict, key: str) -> str:
    val = env.get(key, "").strip()
    if not val:
        print(f"ERROR: {key} is not set in .env")
        sys.exit(1)
    return val

def get(env: dict, key: str, default: str = "") -> str:
    return env.get(key, "").strip() or default

# ---------------------------------------------------------------------------
# HTTP helpers
# ---------------------------------------------------------------------------
def arr_get(base: str, key: str, path: str) -> dict:
    r = requests.get(f"{base}{path}", headers={"X-Api-Key": key}, timeout=15)
    r.raise_for_status()
    return r.json()

def arr_post(base: str, key: str, path: str, body: dict) -> dict:
    r = requests.post(
        f"{base}{path}", json=body,
        headers={"X-Api-Key": key, "Content-Type": "application/json"},
        timeout=15
    )
    r.raise_for_status()
    return r.json()

def arr_put(base: str, key: str, path: str, body: dict) -> dict:
    r = requests.put(
        f"{base}{path}", json=body,
        headers={"X-Api-Key": key, "Content-Type": "application/json"},
        timeout=15
    )
    r.raise_for_status()
    return r.json()

def already_exists(base: str, key: str, list_path: str, name_field: str, name: str) -> bool:
    try:
        items = arr_get(base, key, list_path)
        return any(str(i.get(name_field, "")).lower() == name.lower() for i in items)
    except Exception:
        return False

def reconcile_fields(existing: dict, *, top_level: Optional[dict] = None,
                     fields: Optional[dict] = None) -> bool:
    """Patch `existing` in place to match desired values; return True if anything
    changed.

    Used to bring previously-bootstrapped *arr download clients and Prowlarr
    application connections in line with current desired state without
    deleting and recreating them (which would lose user-side history). Both
    *arrs and Prowlarr expose configuration objects with two layers — top-
    level flags (`removeCompletedDownloads`, `enable`, …) and a `fields`
    array of `{name, value}` dicts. We diff each layer separately.
    """
    changed = False
    for k, v in (top_level or {}).items():
        if existing.get(k) != v:
            existing[k] = v
            changed = True
    if fields:
        for f in existing.get("fields", []):
            name = f.get("name")
            if name in fields and f.get("value") != fields[name]:
                f["value"] = fields[name]
                changed = True
    return changed

def wait_for(url: str, label: str, timeout: int = 180) -> None:
    """Poll until `url` responds with a non-5xx, or bail after `timeout` seconds.

    Exponential backoff with a 15s ceiling. A connection error means the
    service hasn't bound its port yet (still starting — keep waiting).
    A 5xx means the service bound a port but is broken (still transient
    during first-boot DB migrations — keep waiting, but surface the detail).
    """
    print(f"  Waiting for {label}...", end="", flush=True)
    deadline = time.time() + timeout
    delay = 1.0
    last_err = None
    while time.time() < deadline:
        try:
            r = requests.get(url, timeout=5)
            if r.status_code < 500:
                print(" ready")
                return
            last_err = f"HTTP {r.status_code}"
        except requests.ConnectionError:
            last_err = "connection refused"
        except requests.Timeout:
            last_err = "timeout"
        except Exception as e:
            last_err = type(e).__name__
        print(".", end="", flush=True)
        time.sleep(delay)
        delay = min(delay * 1.5, 15.0)
    print(f"\nERROR: {label} did not come up within {timeout}s (last: {last_err})")
    sys.exit(1)

# ---------------------------------------------------------------------------
# Configure an *arr app: root folder + SABnzbd client + media management
# ---------------------------------------------------------------------------
def configure_arr(label: str, base: str, key: str, root_folder: str,
                  sabnzbd_category: str, sabnzbd_key: str,
                  extra_mm: Optional[dict] = None) -> None:

    # Each *arr names the SABnzbd category field differently.
    # Source of truth: /api/<ver>/downloadclient/schema → fields[].name where
    # implementation == "Sabnzbd". Passing the wrong name 400s the request.
    category_field = {
        "Radarr": "movieCategory",
        "Sonarr": "tvCategory",
        "Lidarr": "musicCategory",
    }[label]

    # Lidarr 2.x is still on the v1 API; Radarr v5 / Sonarr v4 are on v3.
    # The wait_for() check uses sub-500 = "ready", so a 404 on the wrong
    # version still passes the up-check — but real config calls 404 here.
    api_ver = "v1" if label == "Lidarr" else "v3"

    # Root folder. Lidarr's POST /rootfolder rejects bare {"path": ...} —
    # it requires a name, default quality + metadata profile IDs, and
    # default monitor options (these get applied to artists added under
    # this root folder). Radarr/Sonarr only need {"path": ...}.
    existing_roots = arr_get(base, key, f"/api/{api_ver}/rootfolder")
    if any(f["path"] == root_folder for f in existing_roots):
        print(f"  ✓ {label}: root folder already set")
    else:
        if label == "Lidarr":
            qprofs = arr_get(base, key, f"/api/{api_ver}/qualityprofile")
            mprofs = arr_get(base, key, f"/api/{api_ver}/metadataprofile")
            # Prefer 'Standard' if Lidarr's stock profiles are present;
            # fall back to the first available so a customised install
            # (someone deleted Standard) still works.
            qid = next((p["id"] for p in qprofs if p["name"] == "Standard"),
                       qprofs[0]["id"])
            mid = next((p["id"] for p in mprofs if p["name"] == "Standard"),
                       mprofs[0]["id"])
            payload = {
                "name": "Music",
                "path": root_folder,
                "defaultQualityProfileId": qid,
                "defaultMetadataProfileId": mid,
                "defaultMonitorOption": "all",
                "defaultNewItemMonitorOption": "all",
                "defaultTags": [],
            }
        else:
            payload = {"path": root_folder}
        arr_post(base, key, f"/api/{api_ver}/rootfolder", payload)
        print(f"  ✓ {label}: root folder → {root_folder}")

    # SABnzbd download client. Desired state captured in desired_top +
    # desired_fields so:
    #   - new installs: full payload constructed from these dicts
    #   - existing installs: reconcile_fields() drives any field that has
    #     drifted from desired (host, port, urlBase, etc.) without losing
    #     unrelated *arr-side state.
    #
    # removeCompletedDownloads=True: after a successful import the *arr tells
    # SAB to remove the job, which is what actually deletes the files under
    # usenet/complete. The *arr is the only component that CAN do this — it
    # is the one that knows the import succeeded and where the file went.
    #
    # This was False, justified by "SAB's history_retention handles cleanup
    # independently". That is wrong. SABnzbd's history retention moves or
    # deletes HISTORY ENTRIES only; upstream is explicit that delete-files was
    # never supported for successfully completed jobs, because sorting rules
    # and user scripts make the final location unknowable to SAB. With this
    # False and nothing else cleaning up, complete/ reached 324 GB across 127
    # job folders on the live box — including _UNPACK_ failures, a _FAILED_
    # job, and five copies of the same episode from repeated re-grabs.
    #
    # The removal fires only after a successful import, so it does not race
    # post-processing. The separate *arr health warning about removing
    # completed downloads concerns the DOWNLOAD CLIENT auto-deleting on its
    # own schedule, which is a different setting and still off.
    #
    # host=gluetun because SAB shares gluetun's netns; from any other
    # container's POV the SAB UI lives at gluetun:8080. Docker DNS for
    # "sabnzbd" doesn't resolve.
    desired_top = {"removeCompletedDownloads": True}
    desired_fields = {
        "host":         "gluetun",
        "port":         8080,
        "apiKey":       sabnzbd_key,
        "urlBase":      "",
        category_field: sabnzbd_category,
        "useSsl":       False,
    }
    existing_clients = arr_get(base, key, f"/api/{api_ver}/downloadclient")
    sab_client = next((c for c in existing_clients if c.get("name") == "SABnzbd"), None)
    if sab_client is not None:
        if reconcile_fields(sab_client, top_level=desired_top, fields=desired_fields):
            arr_put(base, key, f"/api/{api_ver}/downloadclient/{sab_client['id']}", sab_client)
            print(f"  ✓ {label}: SABnzbd reconciled")
        else:
            print(f"  ✓ {label}: SABnzbd already connected")
    else:
        arr_post(base, key, f"/api/{api_ver}/downloadclient", {
            "enable": True,
            "protocol": "usenet",
            "priority": 1,
            "name": "SABnzbd",
            **desired_top,
            "fields": [{"name": k, "value": v} for k, v in desired_fields.items()],
            "implementationName": "SABnzbd",
            "implementation": "Sabnzbd",
            "configContract": "SabnzbdSettings",
            "tags": []
        })
        print(f"  ✓ {label}: SABnzbd download client added (category: {sabnzbd_category})")

    # Media management: enable hardlinks, import extra files
    try:
        current = arr_get(base, key, f"/api/{api_ver}/config/mediamanagement")
        updated = {**current,
                   "copyUsingHardlinks": True,
                   "deleteEmptyFolders": True,
                   "importExtraFiles": True,
                   **(extra_mm or {})}
        arr_put(base, key, f"/api/{api_ver}/config/mediamanagement", updated)
        print(f"  ✓ {label}: hardlinks enabled")
    except Exception as e:
        print(f"  ⚠ {label}: media management update failed: {e}")

